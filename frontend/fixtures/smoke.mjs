import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import { chromium } from 'playwright'

const base = process.env.SMOKE_URL || 'http://127.0.0.1:5173'
const browser = await chromium.launch({ channel: process.env.SMOKE_BROWSER || 'msedge', headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
const apiRequests = []
const errors = []
page.on('request', request => { if (new URL(request.url()).pathname.startsWith('/api/')) apiRequests.push(request.url()) })
page.on('pageerror', error => errors.push(error.message))
await mkdir('.artifacts', { recursive: true })
const fits = async () => assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'No horizontal overflow')
const shot = async name => {
  await page.waitForTimeout(250) // let the theme's short color transitions settle before capturing
  await page.screenshot({ path: `.artifacts/${name}.png` })
}

try {
  await page.goto(`${base}/?mock=1`)
  await page.getByText('Sample workspace — scenes use placeholder videos.', { exact: true }).waitFor()
  const liveLink = await page.getByRole('link', { name: 'Open live workspace' }).getAttribute('href')
  assert.equal(new URL(liveLink).searchParams.has('mock'), false)
  await page.evaluate(() => document.fonts.ready)
  await page.getByRole('heading', { name: 'Ideas, beautifully told.' }).waitFor()
  assert.ok(await page.getByRole('button', { name: 'Create reel', exact: true }).isDisabled())
  assert.equal(await page.locator('html').getAttribute('data-theme'), 'dark')
  assert.ok(await page.locator('.feature-image').evaluate(image => image.naturalWidth > 0))
  await fits()
  await shot('theme-home')
  // The image opens a real, dismissible topic dialog, not a fake video player.
  await page.getByRole('button', { name: 'Explore Beyond Earth' }).click()
  await page.getByRole('dialog').waitFor()
  await page.keyboard.press('Escape')
  assert.equal(await page.getByRole('dialog').count(), 0)
  await page.getByRole('button', { name: 'Explore Beyond Earth' }).click()
  await page.getByRole('button', { name: 'Use this topic', exact: true }).click()
  assert.equal(await page.getByLabel('Your topic').inputValue(), "What are Saturn's rings made of?")
  assert.ok(await page.getByLabel('Your topic').evaluate(input => input === document.activeElement))
  await page.getByRole('button', { name: 'Light theme', exact: true }).click()
  assert.equal(await page.locator('html').getAttribute('data-theme'), 'light')
  await page.reload()
  assert.equal(await page.locator('html').getAttribute('data-theme'), 'light')
  await shot('theme-home-light')
  await page.getByRole('button', { name: 'Dark theme', exact: true }).click()
  await page.getByRole('button', { name: 'How ResearchReel works' }).click()
  await page.getByRole('dialog').waitFor()
  await page.getByRole('button', { name: 'Got it' }).click()
  await page.getByRole('button', { name: 'Projects', exact: true }).click()
  await page.getByRole('heading', { name: 'Ideas in motion.' }).waitFor()
  assert.equal(await page.getByRole('button', { name: 'Current reel', exact: true }).isDisabled(), true)
  await shot('theme-empty-library')
  await page.getByRole('button', { name: 'Collapse sidebar' }).click()
  assert.equal(await page.locator('.sidebar-rail-nav button').count(), 2)
  await page.locator('.sidebar').getByRole('button', { name: 'New reel', exact: true }).click()
  await page.getByLabel('Your topic').fill('How does WhatsApp voice calling infrastructure work?')
  await page.setViewportSize({ width: 1366, height: 708 })
  await fits()
  assert.ok(await page.locator('.topic-form').evaluate(element => element.getBoundingClientRect().bottom < innerHeight))
  await page.getByRole('button', { name: 'Create reel', exact: true }).click()
  await page.locator('.project-item').first().waitFor()
  await page.getByRole('button', { name: 'Expand sidebar' }).click()
  await page.getByText('Research & sources', { exact: true }).waitFor()
  await page.getByText('The conversation', { exact: true }).waitFor()
  await page.getByText('Audio & word timing', { exact: true }).first().waitFor()
  await page.getByText('6/6 ready', { exact: true }).waitFor({ timeout: 30000 })
  const scenes = page.locator('.scene-card')
  assert.equal(await scenes.count(), 6)
  assert.deepEqual(await scenes.locator('.scene-number').allTextContents(), ['01', '02', '03', '04', '05', '06'])
  const readyEvents = await page.locator('.activity-event').filter({ hasText: 'preview ready' }).allTextContents()
  assert.deepEqual(readyEvents.map(text => Number(text.match(/Scene (\d)/)?.[1])), [3, 1, 6, 2, 5, 4])
  await page.setViewportSize({ width: 1440, height: 900 })
  await fits()
  await shot('theme-editor')
  await page.getByRole('button', { name: /Research & sources/ }).click()
  assert.equal(await page.locator('.source-list a').count(), 2)
  await page.locator('.audio-details summary').first().click()
  assert.ok(await page.locator('.word-list').first().isVisible())
  await shot('theme-research-audio')
  await page.getByRole('button', { name: 'Light theme', exact: true }).click()
  await shot('theme-editor-light')
  await page.getByRole('button', { name: 'Dark theme', exact: true }).click()

  const before = await scenes.locator('video').evaluateAll(elements => elements.map(element => element.getAttribute('src')))
  await scenes.nth(5).locator('.scene-select').click()
  await page.getByRole('textbox', { name: 'Scene correction' }).fill('Please correct scene six: make the packet diagram clearer')
  await page.getByRole('button', { name: 'Send correction' }).click()
  await scenes.nth(5).getByText(/Version 2/).waitFor({ timeout: 12000 })
  const after = await scenes.locator('video').evaluateAll(elements => elements.map(element => element.getAttribute('src')))
  assert.deepEqual(after.slice(0, 5), before.slice(0, 5))
  assert.notEqual(after[5], before[5])
  await shot('theme-revised')

  await page.getByRole('button', { name: 'Stitch reel', exact: true }).click()
  await page.getByRole('progressbar', { name: 'Final render', exact: true }).waitFor()
  await shot('theme-rendering')
  await page.getByRole('link', { name: 'Download MP4' }).waitFor({ timeout: 12000 })
  await page.reload()
  await page.getByRole('link', { name: 'Download MP4' }).waitFor()
  assert.equal(await scenes.count(), 6)
  await shot('theme-stitched')
  await page.getByRole('button', { name: 'Project overview' }).click()
  assert.equal(await page.locator('.overview-project').count(), 1)
  await page.getByLabel('Search projects').fill('not-a-matching-title')
  await page.getByRole('heading', { name: 'No stories found.' }).waitFor()
  await page.getByRole('button', { name: 'Clear filters' }).click()
  await page.getByRole('button', { name: 'Completed', exact: true }).click()
  assert.equal(await page.locator('.overview-project').count(), 1)
  await shot('theme-library')
  await page.getByRole('button', { name: 'Current reel', exact: true }).click()

  for (const width of [768, 390, 320]) {
    await page.setViewportSize({ width, height: 844 })
    await fits()
    if (width <= 700) await page.getByRole('button', { name: 'Scenes', exact: true }).click()
    assert.ok(await scenes.first().isVisible())
    await shot(`theme-editor-${width}`)
  }
  await page.getByRole('button', { name: 'Activity & dialogue' }).click()
  await shot('theme-mobile-dialogue')
  await page.getByRole('button', { name: 'New reel', exact: true }).click()
  await page.getByRole('heading', { name: 'Ideas, beautifully told.' }).waitFor()
  await fits()
  await shot('theme-home-mobile')
  assert.deepEqual(apiRequests, [])
  assert.deepEqual(errors, [])
  console.log(JSON.stringify({ theme: 'all views, dark + light', slots: [1, 2, 3, 4, 5, 6], completion_order: [3, 1, 6, 2, 5, 4], scene_6_revision: 2, other_preview_urls_unchanged: true, stitch_download: true, refresh_restored: true, project_search_filters: true, mobile_navigation: true, no_horizontal_overflow: true, api_requests: apiRequests.length, browser_errors: errors.length }))
} finally { await browser.close() }
